"""A83 threshold sweep: how many history comparisons an outlet needs before the site draws it. For each candidate
minimum: the outlets kept, and the agreement of the latest positions with AllSides and DNR (external_check's tests,
econ + social, on the kept outlets only). Only reading.

    PYTHONPATH=. uv run python -m pipeline.history.threshold          → prints, and writes reports/threshold.md

Counts are the history's comparisons without foreign editions (A81, pipeline.history.prior.comparisons). A DNR country
needs two kept outlets (its scores are compared within the country).
"""
from __future__ import annotations

import csv
import json
import sqlite3
from pathlib import Path

import numpy as np

from pipeline.history import external_check as X
from pipeline.history.prior import comparisons
from pipeline.sources.registry import load_outlets

OUT = Path("reports/threshold.md")
GRID = (0, 500, 1000, 2000, 3000, 4000, 5000, 6000, 8000, 10000, 15000, 20000)


def main():
    conn = sqlite3.connect(f"file:{X.DB}?mode=ro", uri=True, timeout=60)
    start, last = X.latest(conn)
    ours = X.averaged(conn, "history_positions", "outlet", start, last)
    n = {o: k for o, (k, _) in comparisons(str(X.DB), last).items()}
    registry = [o.id for o in load_outlets()]
    rated = json.loads(Path("docs/experiments/e4_prereg.json").read_text())["allsides"]["ratings"]
    dnr = [r for r in csv.DictReader((X.REF / "dnr2017_audience_leaning.csv").open()) if r["outlet"] in ours]
    L = ["# A83 — how many comparisons before an outlet is drawn", "",
         f"History positions on {last}; comparisons without foreign editions (A81). ρ = Spearman, econ + social, "
         f"[95 % bootstrap, {X.BOOT} resamples]. Generated by `python -m pipeline.history.threshold`.", "",
         "| min comparisons | outlets drawn | AllSides ρ (n) | DNR within country ρ (n outlets, countries) |",
         "|---:|---:|---|---|"]
    for t in GRID:
        keep = {o for o in registry if n.get(o, 0) >= t}
        rs = [(o, x) for o, x in rated.items() if o in ours and o in keep]
        a = X.boot_ci([[(x, ours[o]["sum"])] for o, x in rs]) if len(rs) >= 4 else None
        by_c: dict[str, list] = {}
        for r in dnr:
            if r["outlet"] in keep:
                by_c.setdefault(r["country"], []).append(r)
        groups = []
        for rows in by_c.values():
            if len(rows) < 2:
                continue
            x = np.array([float(r["cross_platform"]) for r in rows]); y = np.array([ours[r["outlet"]]["sum"] for r in rows])
            groups.append(list(zip(x - x.mean(), y - y.mean())))
        d = X.boot_ci(groups) if len(groups) >= 3 else None
        cell = lambda v, k: f"{v[0]:+.2f} [{v[1]:+.2f}, {v[2]:+.2f}] ({k})" if v else f"— ({k})"   # noqa: E731
        L.append(f"| {t:,} | {len(keep)} of {len(registry)} ({len(keep) / len(registry):.0%}) | {cell(a, len(rs))} | "
                 f"{cell(d, f'{sum(len(g) for g in groups)}, {len(groups)}')} |")
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L[4:]))
    print(f"→ {OUT}")


if __name__ == "__main__":
    main()
